<?php

session_start();


/*
|--------------------------------------------------------------------------
| CLAVE DEL CARRITO
|--------------------------------------------------------------------------
*/

$clave = $_GET['clave'] ?? '';


/*
|--------------------------------------------------------------------------
| ELIMINAR POR CLAVE
|--------------------------------------------------------------------------
*/

if ($clave !== '') {

    if (isset($_SESSION['carrito'][$clave])) {

        unset($_SESSION['carrito'][$clave]);

    }

} else {


    /*
    |--------------------------------------------------------------------------
    | COMPATIBILIDAD CON EL CARRITO ANTERIOR
    |--------------------------------------------------------------------------
    */

    if (isset($_GET['id'])) {

        $id = (int)$_GET['id'];

        if (isset($_SESSION['carrito'][$id])) {

            unset($_SESSION['carrito'][$id]);

        }

    }

}


header("Location: index.php");

exit;